bool _inside(List<Offset> poly, Offset p) {
  var inside = false;
  for (var i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    final pi = poly[i], pj = poly[j];
    if ((pi.dy > p.dy) != (pj.dy > p.dy) &&
        p.dx < (pj.dx - pi.dx) * (p.dy - pi.dy) / (pj.dy - pi.dy) + pi.dx) {
      inside = !inside;
    }
  }
  return inside;
}

CampusPlace? placeAt(Offset normalized) {
  CampusPlace? best;
  var bestD = double.infinity;
  for (final shape in kCampusShapes) {
    if (!_inside(shape.points, normalized)) continue;
    for (final name in shape.names) {
      for (final place in kCampusPlaces) {
        if (place.name != name) continue;
        final d = (place.anchor - normalized).distance;
        if (d < bestD) {
          bestD = d;
          best = place;
        }
      }
    }
  }
  return best;
}
